using WithLithum.NativeWrapperGen.Models;

namespace WithLithum.NativeWrapperGen.Generation;

partial class WrapperFileGenerator
{
    private readonly IShimGenerator _shimGenerator;
    private readonly GeneratorSettings _settings;
    private readonly TextWriter _writer;

    public WrapperFileGenerator(TextWriter writer,
        GeneratorSettings settings, IShimGenerator shimGenerator)
    {
        _writer = writer;
        _settings = settings;
        _shimGenerator = shimGenerator;
    }

    private string GetStringForType(ScriptCommandReturnType returnType)
    {
        return _settings.TypeSettings.GetTypeName(returnType);
    }

    private WrapperEmitContext CreateContext(string hash, ScriptCommandInfo commandInfo)
    {
        return new WrapperEmitContext
        {
            Hash = hash,
            SymbolNameHash = MethodNameConverter.HashToMethodName(hash),
            CommandInfo = commandInfo,
            ReturnTypeString = GetStringForType(commandInfo.ReturnType)
        };
    }

    public void WritePartial(string nameSpace,
        string className,
        IReadOnlyDictionary<string, ScriptCommandInfo> partial)
    {
        _writer.WriteLine("// <auto-generated />");

        WriteNameSpaceScopeHeader(nameSpace);
        WriteClassScopeHeader(className);

        foreach (var command in partial)
        {
            _shimGenerator.WriteMethod(CreateContext(command.Key, command.Value),
                _writer);
        }

        WriteScopeFooter(); // end class
        WriteScopeFooter(); // end namespace
    }
}
